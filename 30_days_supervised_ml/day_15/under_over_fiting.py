# Bias = Error due to too simple assumptions 
# Variance = Error due to too much sensitivity to data

# In Machine Learning, your goal is:
# Build a model that learns patterns, not just memorizes data.

# Underfitting (High Bias)
# Model is too simple
# Cannot capture real patterns

# Overfitting (High Variance)

# Model is too complex
# Memorizes training data


# Student Example

# Type	Behavior
# Underfitting	Student didn’t study → fails everywhere
# Good Fit	Student understands concepts
# Overfitting	Student memorizes answers → fails in new questions